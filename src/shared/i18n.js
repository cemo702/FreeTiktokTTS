export const DEFAULT_LANGUAGE = 'tr';

/** OS diline gore cozumler ('tr-TR' -> 'tr'). */
export function detectSystemLanguage(locale = null) {
  const raw = locale ?? (globalThis.navigator?.language ?? globalThis.process?.env?.LANG ?? 'tr');
  const code = String(raw).toLowerCase().split(/[-_.@]/)[0];
  return MESSAGES[code] ? code : DEFAULT_LANGUAGE;
}

/** 'system' degerini gercek bir dile cevirir. */
export function resolveLanguage(value, systemLocale = null) {
  if (value === 'system' || !value) return detectSystemLanguage(systemLocale);
  return MESSAGES[value] ? value : DEFAULT_LANGUAGE;
}

/** Anahtar var mi? (i18n butunluk testleri kullanir) */
export function hasKey(lang, key) {
  return Object.prototype.hasOwnProperty.call(MESSAGES[lang] ?? {}, key);
}

export function createTranslator(lang = DEFAULT_LANGUAGE) {
  const active = MESSAGES[lang] ? lang : DEFAULT_LANGUAGE;
  const t = (key, vars = null) => {
    let value = MESSAGES[active]?.[key];
    if (value === undefined) {
      if (active !== DEFAULT_LANGUAGE) value = MESSAGES[DEFAULT_LANGUAGE][key];
      if (value === undefined) {
        if (globalThis.console) console.warn(`[i18n] eksik anahtar: ${key}`);
        return key;
      }
    }
    if (!vars) return value;
    return value.replace(/\{(\w+)\}/g, (match, name) =>
      (vars[name] === undefined || vars[name] === null ? match : String(vars[name])));
  };
  t.lang = active;
  return t;
}

export default MESSAGES;
